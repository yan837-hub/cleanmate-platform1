SELECT '=== 用户分布 ===' AS '';
SELECT role, COUNT(*) cnt,
  CASE role WHEN 1 THEN '顾客' WHEN 2 THEN '保洁员' WHEN 3 THEN '管理员' END role_name
FROM user WHERE id >= 1001 GROUP BY role;

SELECT '=== 订单状态分布 ===' AS '';
SELECT status,
  CASE status WHEN 1 THEN '待派单' WHEN 2 THEN '已派单待确认' WHEN 3 THEN '已接单'
    WHEN 4 THEN '服务中' WHEN 5 THEN '待确认完成' WHEN 6 THEN '已完成'
    WHEN 7 THEN '售后中' WHEN 8 THEN '已取消' WHEN 9 THEN '改期审核中' END status_name,
  COUNT(*) cnt
FROM service_order WHERE id BETWEEN 3001 AND 3015 GROUP BY status ORDER BY status;

